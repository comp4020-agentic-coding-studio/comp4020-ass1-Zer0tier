const sharedAssets: SystemAssetMap = {
  drive: "system-icons/WindowsFloppyDrive.png",
  disk: "system-icons/WindowsHardDrive.png",
  cd: "system-icons/WindowsCDROMDrive.png",
};

export function getWindowsSystemAssetStyle(releaseId: WindowsRelease["id"], base: string) {
  return Object.entries({ ...sharedAssets, ...releaseAssets[releaseId] })
    .map(([name, path]) => `--system-${name}:url("${base}media/${path}")`)
    .join(";");
}
